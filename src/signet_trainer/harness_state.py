def project_root(explicit: Path | None = None) -> Path:
    """The project root that owns the LIVE harness state (the dir holding ``.planning/harness``).

    Resolution order, first hit wins:

      1. ``explicit`` — what a caller passed (tests, ``emit_all(repo_root=...)``).
      2. ``SIGNET_PROJECT_ROOT`` — the explicit env override.
      3. the nearest ancestor of the CWD that carries ``.planning/harness`` (the normal case: the
         harness CLI is run from somewhere inside the project).
      4. ``REPO_ROOT`` — the checkout this module lives in (correct only for a source checkout).

    Never raises: a root is always returned so the CALLER can name the specific missing artifact.
    """
    if explicit is not None:
        return Path(explicit)
    env = os.environ.get(PROJECT_ROOT_ENV_VAR, "").strip()
    if env:
        return Path(env)
    cwd = Path.cwd().resolve()
    for candidate in (cwd, *cwd.parents):
        if (candidate / PLANNING_HARNESS_DIR).is_dir():
            return candidate
    return REPO_ROOT


def _missing_live_state(lead: str, root: Path) -> str:
    """The one actionable message for absent LIVE state — never a bare stack trace.

    ``lead`` is the caller's own first line (kept verbatim so existing error contracts hold); this
    appends WHERE the project root came from and HOW to point it somewhere else.
    """
    return (
        f"{lead}\n"
        f"    resolved against project root {root} (live harness state is PROJECT-relative and is "
        f"deliberately NOT shipped with the package).\n"
        f"    fix: run this from inside a signet-trainer project (a directory carrying "
        f"{PLANNING_HARNESS_DIR}/), or set {PROJECT_ROOT_ENV_VAR}=/path/to/project."
    )


def discover_campaign_state_path(repo_root: Path | None = None) -> str:
    """Repo-relative posix path of the ACTIVE campaign's ``.state.yaml`` card. Fails LOUD.

    Discovery, not configuration-by-code: glob ``cards/TRAINING-CARD-*.state.yaml`` under
    ``repo_root``. Exactly one card == the active campaign. With multiple cards the
    ``SIGNET_CAMPAIGN`` env var must name the active slug (``TRAINING-CARD-<slug>.state.yaml``);
    zero cards (or a pinned slug with no card) raises ``FileNotFoundError``; an unpinned
    multi-card dir raises ``ValueError`` listing the candidates. No campaign name is ever
    hardcoded here.
    """
    root = project_root(repo_root)
    cards_dir = root / CARDS_DIR
    pattern = f"{CARD_STATE_PREFIX}*{CARD_STATE_SUFFIX}"
    candidates = sorted(cards_dir.glob(pattern))
    slug = os.environ.get(CAMPAIGN_ENV_VAR)
    if slug:
        pinned = cards_dir / f"{CARD_STATE_PREFIX}{slug}{CARD_STATE_SUFFIX}"
        if not pinned.is_file():
            raise FileNotFoundError(
                f"{CAMPAIGN_ENV_VAR}={slug!r} names no campaign card: {pinned} not found "
                f"(available: {[c.name for c in candidates]})"
            )
        return (Path(CARDS_DIR) / pinned.name).as_posix()
    if not candidates:
        raise FileNotFoundError(
            _missing_live_state(
                f"no campaign card found: {cards_dir}/{pattern} matched nothing — create the "
                f"campaign's typed card (TS-01b) before emitting",
                root,
            )
        )
    if len(candidates) > 1:
        raise ValueError(
            f"multiple campaign cards found in {cards_dir}: {[c.name for c in candidates]} — "
            f"set {CAMPAIGN_ENV_VAR}=<slug> to pin the active campaign (never guessed)"
        )
    return (Path(CARDS_DIR) / candidates[0].name).as_posix()


def campaign_card_md_path(state_rel_path: str) -> str:
    """The campaign card's companion prose ``.md`` artifact for a ``.state.yaml`` relpath."""
