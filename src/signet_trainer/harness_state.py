"""Typed-state emitter (TS-01a + TS-01b) — prose artifacts embed GENERATED state, never hand-copies.

"Typed State Beats Prose" (KNOWLEDGE `typed-state`, operator-adopted 2026-07-14): under cascaded
compaction, prose summaries corrupted 36.4% of numeric probes vs 9.4% for typed ``name: value``
blocks. The in-house failure this kills: the $250-vs-$260 ledger drift, where hand-copied
prose figures staled while the typed SESSION-STATE.json stayed right. Rule: never paraphrase a
computed value where a ``name: value`` line carries it verbatim.

This module renders the ``TYPED-STATE`` blocks embedded in prose artifacts (training card,
``.continue-here.md``, ``STATE.md`` Session Continuity) FROM the typed sources of truth:

Two classes of source, addressed two different ways (the packaging split): SPEC/TEMPLATE files ship
as PACKAGE DATA (``signet_trainer.harness_data``, resolved via ``importlib.resources`` so they work
from an installed wheel with no ``.planning/`` on disk); LIVE per-project state stays under
``.planning/harness/`` and is resolved against ``project_root()``, which fails with an actionable
message rather than a stack trace when there is no project.

  * ``.planning/harness/cards/<card>.state.yaml`` (LIVE) — the typed campaign core (TS-01b):
    campaign identity, per-round records, and the live ``current`` slots. Edit THAT file, never
    the emitted blocks.
  * ``.planning/harness/SESSION-STATE.json`` (LIVE) — the SINGLE numeric source of truth for spend/cap.
    The spent figure is read via ``signet_trainer.modal.session_cap.read_ledger`` (the one
    authoritative ledger reader — never re-summed ad hoc); ``session_cap_usd`` and the entry
    count are read from the same JSON directly because ``session_cap`` exposes no getter for them.
  * ``HOUSE-SPEC.yaml`` (PACKAGED — ``signet_trainer.harness_data``) — the typed home of the house VERDICT spec (D-29): the
    locked eval params (``frame_count`` / ``num_inference_steps`` / ``guidance_scale`` / ``seed`` /
    ``two_stage_upscale`` / ``min_prompt_count``) that ``assert_verdict_spec`` asserts a verdict
    render against. These are DELIBERATELY different from ``schema.py::ValidationConfig`` defaults
    (the LTX-canonical params) — schema.py stays zero-edit; the divergence is intentional (Plan 01
    F-3). ``load_house_spec`` reads it, fail-LOUD.
  * ``TIER-TAXONOMY.yaml`` (PACKAGED — ``signet_trainer.harness_data``) — the knob->tier partition (D-30 part 1). The
    KNOWLEDGE.md knob->tier table is EMITTED from it via ``render_tier_table`` (D-30 part 2 — the
    drift fence: a hand-written table beside the YAML would silently diverge). ``load_tier_taxonomy``
    reads it, fail-LOUD.

Ownership boundary inside prose artifacts — the marker convention::

    <!-- TYPED-STATE:BEGIN (generated by signet_trainer.harness_state — edit the SOURCES, not this block) -->
    ...emitted yaml code-fence...
    <!-- TYPED-STATE:END -->

``emit_into`` REPLACES only the content between the markers (creating the marker section right
after a named anchor heading when absent), is idempotent (same block twice -> byte-identical
file), and FAILS LOUD on malformed/nested/unbalanced markers rather than guessing. Everything
outside the markers (findings, corrections, verdicts, narrative) is human prose and is never
touched.

Import-confined (Anti-Pattern 6): yaml/json/stdlib + ``signet_trainer.modal.session_cap`` (itself
pure stdlib — verified: importing it pulls neither ``modal`` nor ``torch``). NO torch, NO modal,
NO network — runs free on Windows/CI.

Config seams:
  * The active campaign card is DISCOVERED, never hardcoded: ``discover_campaign_state_path``
    globs ``cards/TRAINING-CARD-*.state.yaml`` under the repo root (exactly one card == the
    active campaign). With MULTIPLE cards, set the ``SIGNET_CAMPAIGN`` env var to the campaign
    slug (the ``<slug>`` in ``TRAINING-CARD-<slug>.state.yaml``) to pin the active one — an
    ambiguous or empty cards dir fails LOUD. ``artifact_registry`` derives the card's companion
    ``.md`` artifact from the discovered state path; the non-campaign artifacts stay in
    ``STATIC_ARTIFACTS``.
  * NO live-Volume source mode is implemented. TS-01a names Volume listings as a potential
    source; that mode is deliberately absent in v1 (it would need a network call — off by
    default and untested-against-network per the house test rules). The typed sources above are
    all local files.

CLI (module runs as ``python -m signet_trainer.harness_state`` from the repo root)::

    PYTHONPATH=src PYTHONUTF8=1 python -m signet_trainer.harness_state emit [--dry-run]

``--dry-run`` prints the rendered block + per-artifact action (replace/create/unchanged) and
writes NOTHING.
"""

